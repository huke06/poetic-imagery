DEFAULT_FAMILY = [("玄青", "#3A4A5A"), ("黛色", "#4A4A56"), ("苍灰", "#6B6B66"), ("缥色", "#7A8A92")]


def _hash_index(key: str, modulo: int) -> int:
    return int(hashlib.md5(key.encode("utf-8")).hexdigest(), 16) % modulo


def assign_color(concept_name: str, category_main: str = "") -> dict:
    """为意象确定性分配传统色（按一级分类色族 + 名称哈希）"""
    family = COLOR_FAMILIES.get(category_main, DEFAULT_FAMILY)
    idx = _hash_index(concept_name, len(family))
    color_name, hex_ = family[idx]
    return {"color": hex_, "color_name": color_name, "family": category_main or "通用"}


def palette_for_category(category_main: str = "") -> list[dict]:
    """返回某一级分类的候选色卡"""
    colors = COLOR_FAMILIES.get(category_main, DEFAULT_FAMILY)
    return [{"color": h, "color_name": n} for n, h in colors]


